# Writes config.inc.php from the environment, then hands over to php-fpm.
#
# The variable names match the upstream phpmyadmin/phpmyadmin image, so an
# existing deployment can swap the image without rewriting its environment.
set -euo pipefail

CONFIG=/var/www/html/config.inc.php

log() { printf '%s entrypoint: %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$*"; }
die() { log "ERROR: $*" >&2; exit 1; }

MARKER='// generated-by: netresearch/phpmyadmin-php-fpm'

# A config.inc.php the operator supplied wins: settings this script does not
# cover must not be overwritten. One this script wrote is regenerated, so a
# changed environment takes effect on restart instead of being ignored
# because the file happens to exist already.
if [ -s "$CONFIG" ] && ! grep -qF "$MARKER" "$CONFIG"; then
    log "config.inc.php was supplied by the operator, leaving it untouched"
    exec "$@"
fi

PMA_HOST=${PMA_HOST:-db}
PMA_PORT=${PMA_PORT:-3306}
PMA_ABSOLUTE_URI=${PMA_ABSOLUTE_URI:-}
PMA_ARBITRARY=${PMA_ARBITRARY:-0}
# Upstream's auto-login pair. Both set switches the server to config auth,
# which puts the credentials in the generated config file — sensible for a
# local database, not for anything reachable by others.
PMA_USER=${PMA_USER:-}
PMA_PASSWORD=${PMA_PASSWORD:-}
UPLOAD_LIMIT=${UPLOAD_LIMIT:-256M}
MEMORY_LIMIT=${MEMORY_LIMIT:-512M}
MAX_EXECUTION_TIME=${MAX_EXECUTION_TIME:-600}

# blowfish_secret encrypts the auth cookie. phpMyAdmin needs exactly 32 bytes
# and logs users out on every restart if it changes, so a generated value must
# be persisted rather than re-rolled. Operators who mount no volume for it get
# a per-start secret and a warning, which is the honest failure mode.
SECRET_FILE=${PMA_SECRET_FILE:-/var/www/html/tmp/blowfish_secret}
if [ -n "${PMA_BLOWFISH_SECRET:-}" ]; then
    BLOWFISH=$PMA_BLOWFISH_SECRET
    [ ${#BLOWFISH} -eq 32 ] || die "PMA_BLOWFISH_SECRET must be exactly 32 characters (got ${#BLOWFISH})"
elif [ -s "$SECRET_FILE" ]; then
    BLOWFISH=$(cat "$SECRET_FILE")
else
    # Deliberately not `tr -dc ... </dev/urandom | head -c 32`: head closes the
    # pipe after 32 bytes, tr dies of SIGPIPE, and under `set -o pipefail` that
    # takes the whole entrypoint down with exit 141 — which is exactly what
    # happens to anyone starting the image without setting the secret.
    raw=$(head -c 48 /dev/urandom | base64)
    raw=${raw//[^A-Za-z0-9]/}
    BLOWFISH=${raw:0:32}
    [ ${#BLOWFISH} -eq 32 ] || die "could not generate a 32-character secret"
    if printf '%s' "$BLOWFISH" > "$SECRET_FILE" 2>/dev/null; then
        log "generated a blowfish secret and stored it in $SECRET_FILE"
    else
        log "WARNING: no PMA_BLOWFISH_SECRET and $SECRET_FILE is not writable —"
        log "WARNING: sessions will be dropped on every restart. Set the variable."
    fi
fi

# Cookie auth asks for credentials; config auth carries them. Only the pair
# switches — one of the two alone would produce a login that cannot succeed.
AUTH_TYPE=cookie
if [ -n "$PMA_USER" ] && [ -n "$PMA_PASSWORD" ]; then
    AUTH_TYPE=config
    log "PMA_USER and PMA_PASSWORD are set: using config auth. The credentials"
    log "land in $CONFIG — intended for a local database, not a shared one."
elif [ -n "$PMA_USER" ] || [ -n "$PMA_PASSWORD" ]; then
    log "only one of PMA_USER/PMA_PASSWORD is set — ignoring both, staying on cookie auth"
    PMA_USER=""
    PMA_PASSWORD=""
fi

log "writing $CONFIG (host $PMA_HOST:$PMA_PORT, auth $AUTH_TYPE, arbitrary=$PMA_ARBITRARY)"
cat > "$CONFIG" <<PHPCONF
<?php
declare(strict_types=1);

${MARKER}

// Generated by the container entrypoint on every start unless a
// config.inc.php is mounted. Edit the environment, not this file.

\$cfg['blowfish_secret'] = '${BLOWFISH}';

\$i = 1;
\$cfg['Servers'][\$i]['host']           = '${PMA_HOST}';
\$cfg['Servers'][\$i]['port']           = '${PMA_PORT}';
\$cfg['Servers'][\$i]['auth_type']      = '${AUTH_TYPE}';
\$cfg['Servers'][\$i]['AllowNoPassword'] = false;
// Arbitrary-server mode lets anyone reaching this UI point it at any host
// the container can route to. Off unless asked for.
\$cfg['AllowArbitraryServer'] = ${PMA_ARBITRARY} === 1 ? true : false;

\$cfg['TempDir']       = '/var/www/html/tmp';
\$cfg['UploadDir']     = '';
\$cfg['SaveDir']       = '';
\$cfg['CheckConfigurationPermissions'] = false;
// The setup wizard is removed from the image; saying so keeps phpMyAdmin
// from advertising a link that 404s.
\$cfg['ShowPhpInfo']   = false;
\$cfg['SendErrorReports'] = 'never';
PHPCONF

# Appended rather than interpolated above, so the password never reaches the
# here-document that is written unconditionally — and so a config without the
# pair carries no empty credential lines at all.
if [ "$AUTH_TYPE" = "config" ]; then
    printf "\$cfg['Servers'][\$i]['user']     = '%s';\n" "$PMA_USER" >> "$CONFIG"
    printf "\$cfg['Servers'][\$i]['password'] = '%s';\n" "$PMA_PASSWORD" >> "$CONFIG"
fi

if [ -n "$PMA_ABSOLUTE_URI" ]; then
    printf "\$cfg['PmaAbsoluteUri'] = '%s';\n" "$PMA_ABSOLUTE_URI" >> "$CONFIG"
fi

# Values PHP reads at startup, not from config.inc.php.
cat > /var/www/php-conf.d/zz-limits.ini <<INI
upload_max_filesize = ${UPLOAD_LIMIT}
post_max_size = ${UPLOAD_LIMIT}
memory_limit = ${MEMORY_LIMIT}
max_execution_time = ${MAX_EXECUTION_TIME}
INI

php -l "$CONFIG" > /dev/null || die "generated config.inc.php is not valid PHP"
log "configuration ready"

exec "$@"
